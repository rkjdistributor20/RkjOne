CREATE OR REPLACE FUNCTION record_factory_raw_material_usage(
 p_production_date DATE,
 p_items JSONB,
 p_notes TEXT DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
 v_user_id UUID;
 v_org_id UUID;
 v_mfg_id UUID;
 v_factory_id UUID;
 v_item JSONB;
 v_stock RECORD;
 v_opening NUMERIC;
 v_received NUMERIC;
 v_used NUMERIC;
 v_closing NUMERIC;
 v_count INT := 0;
BEGIN
 v_user_id := auth.uid();
 IF v_user_id IS NULL THEN RAISE EXCEPTION 'Not authenticated'; END IF;
 IF public.user_role() NOT IN ('SUPER_ADMIN', 'ADMIN', 'CEO_FACTORY') THEN
 RAISE EXCEPTION 'Hanya pentadbir atau staf kilang boleh rekod bahan mentah';
 END IF;

 SELECT organization_id INTO v_org_id FROM profiles WHERE id = v_user_id;
 IF v_org_id IS NULL THEN RAISE EXCEPTION 'Profil tidak lengkap'; END IF;

 SELECT id INTO v_mfg_id FROM legal_entities WHERE organization_id = v_org_id AND code = 'RKJ_MFG' LIMIT 1;

 SELECT id INTO v_factory_id
 FROM inventory_locations
 WHERE organization_id = v_org_id AND location_type = 'FACTORY' AND is_active = true
 ORDER BY CASE WHEN name ILIKE '%bahan%' OR name ILIKE '%manufacturing%' THEN 0 ELSE 1 END, created_at
 LIMIT 1;

 IF v_factory_id IS NULL THEN
 INSERT INTO inventory_locations (organization_id, location_type, name)
 VALUES (v_org_id, 'FACTORY', 'Kilang RKJ Manufacturing - Bahan Mentah')
 RETURNING id INTO v_factory_id;
 END IF;

 IF p_items IS NULL OR jsonb_array_length(p_items) = 0 THEN
 RAISE EXCEPTION 'Sekurang-kurangnya satu bahan diperlukan';
 END IF;

 FOR v_item IN SELECT * FROM jsonb_array_elements(p_items)
 LOOP
 SELECT * INTO v_stock FROM stock_items
 WHERE id = (v_item->>'stock_item_id')::uuid
 AND organization_id = v_org_id
 AND category = 'Bahan Mentah Kilang';

 IF NOT FOUND THEN RAISE EXCEPTION 'Bahan mentah tidak dijumpai'; END IF;

 SELECT COALESCE(quantity, 0) INTO v_opening
 FROM inventory_balances
 WHERE location_id = v_factory_id AND stock_item_id = v_stock.id;
 v_opening := COALESCE(v_opening, 0);

 v_received := COALESCE(NULLIF(v_item->>'received_qty', '')::numeric, 0);
 v_used := COALESCE(NULLIF(v_item->>'used_qty', '')::numeric, 0);
 IF v_received < 0 OR v_used < 0 THEN RAISE EXCEPTION 'Kuantiti tidak boleh negatif'; END IF;

 IF v_received > 0 THEN
 INSERT INTO stock_movements (
 organization_id, movement_type, location_id, stock_item_id,
 quantity, unit, reference_type, notes, created_by, production_date
 ) VALUES (
 v_org_id, 'RECEIVE', v_factory_id, v_stock.id,
 v_received, v_stock.base_unit, 'factory_raw_material', p_notes, v_user_id, p_production_date
 );
 END IF;

 IF v_used > 0 THEN
 INSERT INTO stock_movements (
 organization_id, movement_type, location_id, stock_item_id,
 quantity, unit, reference_type, notes, created_by, production_date
 ) VALUES (
 v_org_id, 'PRODUCTION', v_factory_id, v_stock.id,
 -v_used, v_stock.base_unit, 'factory_raw_material_usage', p_notes, v_user_id, p_production_date
 );
 END IF;

 SELECT COALESCE(quantity, 0) INTO v_closing
 FROM inventory_balances
 WHERE location_id = v_factory_id AND stock_item_id = v_stock.id;
 v_closing := COALESCE(v_closing, v_opening + v_received - v_used);

 INSERT INTO factory_raw_material_stock_cards (
 organization_id, legal_entity_id, location_id, stock_item_id,
 stock_date, production_date, stock_in_qty, stock_out_qty, balance_qty,
 unit_label, measurement_note, source_ref, recorded_by, notes
 ) VALUES (
 v_org_id, v_mfg_id, v_factory_id, v_stock.id,
 p_production_date, p_production_date,
 v_opening + v_received, v_used, v_closing,
 COALESCE(v_stock.storage_unit, v_stock.base_unit::text), v_stock.conversion_text,
 'RKJ One Production Dashboard', v_user_id, p_notes
 )
 ON CONFLICT (organization_id, stock_item_id, stock_date) DO UPDATE SET
 stock_in_qty = EXCLUDED.stock_in_qty,
 stock_out_qty = EXCLUDED.stock_out_qty,
 balance_qty = EXCLUDED.balance_qty,
 unit_label = EXCLUDED.unit_label,
 recorded_by = EXCLUDED.recorded_by,
 notes = EXCLUDED.notes,
 updated_at = now();

 v_count := v_count + 1;
 END LOOP;

 PERFORM check_low_stock(v_org_id);

 RETURN jsonb_build_object(
 'location_id', v_factory_id,
 'production_date', p_production_date,
 'recorded_count', v_count
 );
END;
$$;

GRANT EXECUTE ON FUNCTION record_factory_raw_material_usage(DATE, JSONB, TEXT) TO authenticated;

COMMENT ON TABLE factory_raw_material_stock_cards IS 'Stok card bahan mentah kilang RKJ Manufacturing: masuk, keluar/usage production, baki dan staf perekod.';
